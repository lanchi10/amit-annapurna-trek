let currentDay = 4;

function openDay(dayNum) {
  if (!daysData[dayNum]) return;
  currentDay = dayNum;

  const render = () => {
    const data = daysData[dayNum];
    document.getElementById('detail-day-tag').innerText = `יום ${data.day}`;
    document.getElementById('detail-alt-badge').innerText = `גובה: ${data.altitude}`;
    document.getElementById('detail-image').src = data.image;
    document.getElementById('detail-image').alt = data.title;
    document.getElementById('detail-date').innerText = `🗓️ תאריך: ${data.date}`;
    document.getElementById('detail-loc').innerText = `📍 מקום לינה: ${data.loc}`;
    document.getElementById('detail-title').innerText = data.title;
    document.getElementById('detail-desc').innerText = data.desc;

    // Highlights
    const listEl = document.getElementById('detail-highlights-list');
    listEl.innerHTML = '';
    data.highlights.forEach(h => {
      const li = document.createElement('li');
      li.innerText = h;
      listEl.appendChild(li);
    });

    // Nav Buttons
    const btnPrev = document.getElementById('btn-prev-day');
    const btnNext = document.getElementById('btn-next-day');

    if (dayNum <= 4) {
      btnPrev.disabled = true;
      btnPrev.innerText = '⬅️ אין יום קודם';
    } else {
      btnPrev.disabled = false;
      btnPrev.innerText = `⬅️ יום ${dayNum - 1}`;
    }

    if (dayNum >= 10) {
      btnNext.disabled = true;
      btnNext.innerText = 'אין יום הבא ➡️';
    } else {
      btnNext.disabled = false;
      btnNext.innerText = `יום ${dayNum + 1} ➡️`;
    }

    // Toggle views
    document.getElementById('list-view').classList.add('hidden');
    const detailView = document.getElementById('detail-view');
    detailView.classList.remove('hidden');
    window.location.hash = `day-${dayNum}`;
  };

  // Modern View Transition support with accessibility focus shift
  if (document.startViewTransition) {
    const transition = document.startViewTransition(render);
    transition.finished.finally(() => {
      document.getElementById('detail-view')?.focus();
    });
  } else {
    render();
    document.getElementById('detail-view')?.focus();
  }
}

function showListView() {
  const render = () => {
    document.getElementById('detail-view').classList.add('hidden');
    document.getElementById('list-view').classList.remove('hidden');
    window.location.hash = '';
  };

  if (document.startViewTransition) {
    const transition = document.startViewTransition(render);
    transition.finished.finally(() => {
      document.getElementById('list-view')?.focus();
    });
  } else {
    render();
    document.getElementById('list-view')?.focus();
  }
}

function prevDay() {
  if (currentDay > 4) {
    openDay(currentDay - 1);
  }
}

function nextDay() {
  if (currentDay < 10) {
    openDay(currentDay + 1);
  }
}

// Hash routing & Keyboard navigation support
window.addEventListener('DOMContentLoaded', () => {
  const hash = window.location.hash;
  if (hash && hash.startsWith('#day-')) {
    const dayNum = parseInt(hash.replace('#day-', ''), 10);
    if (dayNum >= 4 && dayNum <= 10) {
      openDay(dayNum);
    }
  }

  document.addEventListener('keydown', (e) => {
    const detailView = document.getElementById('detail-view');
    if (detailView && !detailView.classList.contains('hidden')) {
      if (e.key === 'ArrowRight') { // RTL: Right arrow goes to previous day
        prevDay();
      } else if (e.key === 'ArrowLeft') { // RTL: Left arrow goes to next day
        nextDay();
      } else if (e.key === 'Escape') {
        showListView();
      }
    }
  });
});
